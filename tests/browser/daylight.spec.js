import {test,expect} from '@playwright/test';
test('daylight follows curtains and projects the closed window grid onto the right surfaces',async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/?texture=painted');
 const air=page.locator('.window-air-light'),floor=page.locator('.right-daylight-ground'),desk=page.locator('.window-desk-light');
 await expect(air).toHaveCSS('opacity','1');await expect(floor).toHaveCSS('opacity','1');await expect(desk).toHaveCSS('opacity','1');
 await expect(page.locator('[data-projection="closed-grid"]')).toHaveCSS('opacity','0');
 await page.screenshot({path:`tmp/calendar-landscape/${info.project.name}-open.png`});
 await page.locator('.window-toggle path').click();
 await expect(air).toHaveCSS('opacity','0');await expect(floor).toHaveCSS('opacity','0.6');
 await expect(page.locator('[data-projection="closed-grid"]')).toHaveCSS('opacity','0.14');
 await expect(page.locator('[data-projection="closed-desk-grid"]')).toHaveCSS('opacity','0.14');
 await expect(page.locator('.window-module')).toHaveAttribute('data-window-open','false');
 await page.screenshot({path:`tmp/calendar-landscape/${info.project.name}-glass.png`});
 await page.locator('.curtain-toggle path').first().click();
 for(const light of [air,floor,desk])await expect(light).toHaveCSS('opacity','0');
 await page.screenshot({path:`tmp/calendar-landscape/${info.project.name}-drawn.png`});
 await page.locator('.curtain-toggle path').click();
 await expect(floor).toHaveCSS('opacity','0.6');await expect(air).toHaveCSS('opacity','0');
 await page.locator('.window-toggle path').click();
 await expect(air).toHaveCSS('opacity','1');
 await page.locator('.curtain-toggle path').first().click();
 for(const light of [air,floor,desk])await expect(light).toHaveCSS('opacity','0');
 await page.locator('.curtain-toggle path').click();
 await expect(air).toHaveCSS('opacity','1');
 await expect(page.locator('.texture-review')).toHaveCount(0);
});
